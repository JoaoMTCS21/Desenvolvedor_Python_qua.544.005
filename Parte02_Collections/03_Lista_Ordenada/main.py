# Lista de cidades

cidades = ["Rio de Janeiro" , "Salvador" , "São Paulo" , "Brasília" , "Cuiabá" , "Natal" , "Belo Horizonte"]

# Ordena a lista

cidades .sort()

# Exibe a lista em ordem alfabética

for cidade in cidades:
    print (cidade)

# Reverte a lista

cidades .sort(reverse=True)

# Exibe a lista em ordem reversa

for cidade in cidades:
    print (cidade)